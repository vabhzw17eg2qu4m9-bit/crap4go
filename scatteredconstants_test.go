// scatteredInFileOnly repeats one string value three times inside function
// bodies of ONE file — the core scattered semantic: distinct-file counting
// must not flag in-file repeats, and body literals register nothing.
const scatteredInFileOnly = `package p

func f() string {
	a := "shared fact"
	b := "shared fact"
	c := "shared fact"
	return a + b + c
}
`

// scatteredBodyUse is one function-body occurrence — not a declaration.
const scatteredBodyUse = `package p

func f() string {
	return "shared fact"
}
`

// scatteredVarDecl is a top-level var with a plain literal initializer —
// a referencable named value and a registry entry.
const scatteredVarDecl = `package p

var sharedFact = "shared fact"
`

// scatteredConstDecl is a top-level const — a registry entry.
const scatteredConstDecl = `package p

const SharedFact = "shared fact"
`

// scatteredLocalConst declares the value inside a function: an isDecl site
// that counts but cannot anchor a cross-file reference.
const scatteredLocalConst = `package p

func f() {
	const k = "shared fact"
	_ = k
}
`

// scatteredConstAndUse declares the value and re-introduces it as a bare
// literal in the same file — the re-introduction flags immediately.
const scatteredConstAndUse = `package p

const SharedFact = "shared fact"

func f() string {
	return "shared fact"
}
`

// scatteredComputedConst declares its value through a computed initializer:
// plain-only registry means the long inner literal is an ordinary site (the
// short one filters below min-length).
const scatteredComputedConst = `package p

const greeting = "hello " + "w"
`

// scatteredExemptPositions uses one string three times in protocol
// positions only: map-literal key, index operand, case label.
const scatteredExemptPositions = `package p

var m = map[string]int{"shared fact": 1}
var v = m["shared fact"]

func f(s string) int {
	switch s {
	case "shared fact":
		return 1
	}
	return 0
}
`

// scatteredImportPath uses the shared value as an import path — a
// structural reference, never a corpus candidate.
const scatteredImportPath = `package p

import "app/shared/fact"

var _ = fact.X
`

// scatteredStructTag uses the shared value inside a struct tag — protocol
// wire vocabulary that cannot reference a constant (Go adaptation).
const scatteredStructTag = "package p\n\ntype T struct {\n\tName string `json:\"shared fact\"`\n}\n"

// scatteredSmallValues repeats small literals: a string below min-length
// and numbers with magnitude at or below min-value (1_00 == 100).
const scatteredSmallValues = `package p

func f() int {
	a := "abc"
	b := 100
	c := 1_00
	return len(a) + b + c
}
`

// scatteredTinyConst filters below min-length: no registration, no sites.
const scatteredTinyConst = `package p

const tiny = "abc"

var use = len(tiny)
`

// scatteredIntBaseA/B/C hold the same integer fact in three spellings:
// a declaring const, then bare literals in hex and plain decimal.
const scatteredIntBaseA = `package p

const MaxSize = 1_000
`

const scatteredIntBaseB = `package p

func f() int {
	return 0x3E8
}
`

const scatteredIntBaseC = `package p

func f() int {
	return 1000
}
`

// scatteredFloatA/B/C hold the same float fact in three spellings.
const scatteredFloatA = `package p

const Ratio = 1_000.5
`

const scatteredFloatB = `package p

func f() float64 {
	return 1000.5
}
`

const scatteredFloatC = `package p

func f() float64 {
	return 1000.50
}
`

// scatteredGeneratedFile carries the generated-code marker — excluded by
// default like upstream's generated-code globs.
const scatteredGeneratedFile = `// Code generated by tool DO NOT EDIT.

package p

var c = "shared fact"
`

// scatteredHugeInt is an integer literal beyond int64: counted, grouped by
// spelling.
const scatteredHugeInt = `package p

func f() int {
	return 99999999999999999999
}
`

// scatteredCharAndImag holds char and imaginary literals — no upstream
// counterpart, never counted.
const scatteredCharAndImag = `package p

func f() (rune, complex128) {
	return 'x', 1i
}
`

// scatteredFloatOverflow is a float literal beyond float64 range: counted,
// grouped by spelling.
const scatteredFloatOverflow = `package p

func f() float64 {
	return 1e999
}
`

// scatteredSmallConst declares a small int (exit-code class) — coincidence
// by the minValue doctrine; it must not seed the corpus constant registry.
const scatteredSmallConst = `package p

const code = 7
`

// scatteredBigConst declares an above-threshold int — its const-decl
// initializer hit goes through the same guards as use-site literals and
// registers the corpus constant.
const scatteredBigConst = `package p

const code = 700
`

// scatteredPrivateAlias holds pure value aliases: private consts whose
// initializer is another constant's bare identifier, top-level and
// function-local (the upstream a314b485 'aliases' rule).
const scatteredPrivateAlias = `package p

const kBase = 800

const kAlias = kBase

func f() {
	const kLocal = kBase
	_ = kLocal
}
`

// scatteredExportedAlias is an exported alias — re-export shims are a
// deliberate API shape and stay exempt.
const scatteredExportedAlias = `package p

const kBase = 800

const KAlias = kBase
`

// scatteredComputedAlias initializes through an expression — computed
// initializers are not aliases.
const scatteredComputedAlias = `package p

const kA = 800

const kB = 900

const kSum = kA + kB
`

// scatteredPredeclaredAlias initializes from Go's predeclared constant
// identifiers: true/false are Go's boolean literals and iota is the enum
// machinery — computed, not aliases (Go adaptation). An iota-block
// continuation has no initializer and nothing to alias.
const scatteredPredeclaredAlias = `package p

const debug = true

const release = false

const (
	first = iota
	second
)
`

// scatteredBlankAlias discards a constant through the blank identifier —
// it introduces no name, so there is no alias to flag.
const scatteredBlankAlias = `package p

const kBase = 800

const _ = kBase
`

// writeScatteredCorpus writes named fixture files under root and returns
// their paths in sorted order.
func writeScatteredCorpus(t *testing.T, root string, files map[string]string) []string {
	t.Helper()
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	paths := make([]string, 0, len(names))
	for _, name := range names {
		path := filepath.Join(root, name)
		writeFile(t, path, files[name])
		paths = append(paths, path)
	}
	return paths
}

// checkScatteredSources runs CheckScatteredConstants over the named
// fixtures and returns the violations as "path:line:message" strings.
// wantChecked asserts the number of files counted (excluded files skipped).
func checkScatteredSources(t *testing.T, files map[string]string, minFiles, wantChecked int) []string {
	t.Helper()
	root := t.TempDir()
	paths := writeScatteredCorpus(t, root, files)
	violations, checked := CheckScatteredConstants(paths, root, minFiles, defaultScatteredMinLength, defaultScatteredMinValue, true)
	if checked != wantChecked {
		t.Fatalf("checked = %d, want %d", checked, wantChecked)
	}
	var got []string
	for _, v := range violations {
		got = append(got, fmt.Sprintf("%s:%d:%s", v.Path, v.Line, v.Message))
	}
	return got
}

// regression names the violation message shape for a constant regression.
func regression(display, name, file string, line int) string {
	return fmt.Sprintf("hardcoded %s duplicates constant `%s` (%s:%d) — reference the constant instead of repeating the literal", display, name, file, line)
}

// scatteredNames the violation message shape for a scattered literal.
func scattered(display string, files, occurrences int) string {
	return fmt.Sprintf("literal %s repeats in %d files (%d occurrences) — extract a shared constant and reference it from every site; verify all occurrences mean the same thing first", display, files, occurrences)
}

