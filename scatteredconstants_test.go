func TestScatteredConstantsPerOccurrenceLines(t *testing.T) {
	root := t.TempDir()
	const twoBodyUses = `package p

func f() string {
	a := "shared fact"
	return a + "shared fact"
}
`
	paths := writeScatteredCorpus(t, root, map[string]string{
		"a.go": twoBodyUses,
		"b.go": twoBodyUses,
		"c.go": twoBodyUses,
	})
	violations, checked := CheckScatteredConstants(paths, root, defaultScatteredMinFiles, defaultScatteredMinLength, defaultScatteredMinValue, true)
	if checked != 3 {
		t.Fatalf("checked = %d, want 3", checked)
	}
	if len(violations) != 6 {
		t.Fatalf("violations = %d, want 6 (one per occurrence)", len(violations))
	}
	for i, v := range violations {
		wantPath := []string{"a.go", "a.go", "b.go", "b.go", "c.go", "c.go"}[i]
		wantLine := []int{4, 5, 4, 5, 4, 5}[i]
		if v.Path != wantPath || v.Line != wantLine {
			t.Errorf("violation %d = %s:%d, want %s:%d", i, v.Path, v.Line, wantPath, wantLine)
		}
	}
}

